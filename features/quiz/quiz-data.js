// دالة لجلب أسئلة موسعة إضافية من API المسابقات الإسلامية عند توفر الاتصال مع ضمان 4 خيارات
async function fetchOnlineQuestions(categorySlug = "hadith", level = 1) {
    if (typeof navigator !== 'undefined' && navigator.onLine === false) {
        return null;
    }
    try {
        const catMap = {
            quran: "tafseer",
            sunnah: "hadith",
            akida: "akida",
            fiqh: "figh",
            history: "history",
            arabia: "arabia"
        };
        const mappedCat = catMap[categorySlug] || "hadith";
        const indexUrl = `https://raw.githubusercontent.com/rn0x/IslamicQuizAPI/main/database/${mappedCat}.json`;
        const res = await fetch(indexUrl, { signal: AbortSignal.timeout(1800) });
        if (!res.ok) return null;
        const catData = await res.json();
        if (!catData.DataArray || catData.DataArray.length === 0) return null;

        const randomGroup = catData.DataArray[Math.floor(Math.random() * catData.DataArray.length)];
        const targetFile = randomGroup.files.find(f => f.level === Number(level)) || randomGroup.files[0];
        if (!targetFile) return null;

        const fileUrl = `https://raw.githubusercontent.com/rn0x/IslamicQuizAPI/main${targetFile.path}`;
        const questionsRes = await fetch(fileUrl, { signal: AbortSignal.timeout(1800) });
        if (!questionsRes.ok) return null;
        const rawQuestions = await questionsRes.json();

        // تجمع كل الإجابات الخاطئة لتغذية الخيار الرابع دائماً إذا كان السؤال يتضمن 3 خيارات
        const wrongPool = [];
        rawQuestions.forEach(item => {
            if (item.answers) {
                item.answers.filter(a => a.t === 0).forEach(a => {
                    if (a.answer && a.answer.length < 55) wrongPool.push(a.answer);
                });
            }
        });

        return rawQuestions.map(item => {
            const correctAnswerObj = item.answers.find(a => a.t === 1) || item.answers[0];
            let choices = item.answers.map(a => a.answer);

            // ضمان وجود 4 خيارات بالضبط لضمان عمل وسيلة حذف إجابتين (50:50) بدقة
            while (choices.length < 4) {
                const candidate = wrongPool.find(ans => !choices.includes(ans));
                if (candidate) {
                    choices.push(candidate);
                } else {
                    choices.push("لا شيء مما ذكر");
                }
            }

            return {
                category: categorySlug,
                level: Number(level),
                question: item.q,
                choices: choices.slice(0, 4),
                answer: correctAnswerObj.answer,
                explanation: `فائدة شرعية موثقة من الدرر السنية حول: ${item.q}`,
                source: "الدرر السنية",
                link: item.link || "https://dorar.net"
            };
        });
    } catch (e) {
        console.warn("تعذر جلب الأسئلة عبر الإنترنت، الاعتماد على البنك المدمج:", e);
        return null;
    }
}
